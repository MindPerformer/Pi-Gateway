export type AccountControlKey = keyof typeof zh

export function useAccountControls() {
    const {locale} = useI18n()

    function c(key: AccountControlKey, values: Record<string, string | number> = {}) {
        const text = locale.value === 'zh-CN' ? zh[key] : en[key]
        return text.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''))
    }

    return {c, locale}
}
