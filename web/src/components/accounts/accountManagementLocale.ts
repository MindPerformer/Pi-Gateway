export function useAccountManagementLocale() {
    const {locale} = useI18n()
    const m = (key: keyof typeof zh, values: Record<string, string | number> = {}) =>
        (locale.value === 'zh-CN' ? zh[key] : en[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''))
    return {m}
}
