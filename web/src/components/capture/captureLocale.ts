export type CaptureTextKey = keyof typeof zh

export function useCaptureLocale() {
    const {locale} = useI18n()

    function c(key: CaptureTextKey, values: Record<string, string | number> = {}) {
        return (locale.value === 'zh-CN' ? zh[key] : en[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''))
    }

    return {c}
}
