export type RuleDebugText = keyof typeof zh

export function debugText(key: RuleDebugText, locale: string, params?: Record<string, string | number>) {
    const text = locale === 'zh-CN' ? zh[key] : en[key]
    return text.replace(/\{(\w+)\}/g, (match, name: string) => params?.[name] === undefined ? match : String(params[name]))
}

export function useRuleDebugLocale() {
    const {locale} = useI18n()
    return {d: (key: RuleDebugText, params?: Record<string, string | number>) => debugText(key, locale.value, params)}
}
