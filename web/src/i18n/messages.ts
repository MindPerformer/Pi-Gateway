const catalogues: Record<Locale, Catalogue> = {
    en,
    'zh-CN': zh,
}

export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
    const catalogue = (catalogues[locale] ?? en) as Record<string, string>
    let message = catalogue[key] ?? (en as Record<string, string>)[key] ?? key
    if (params) {
        for (const [name, value] of Object.entries(params)) {
            message = message.replaceAll(`{${name}}`, String(value))
        }
    }
    return message
}

/** Detect the initial locale from the browser, defaulting to English. */
export function detectLocale(): Locale {
    const stored = localStorage.getItem('pi-gateway-locale')
    if (stored === 'en' || stored === 'zh-CN') return stored
    const language = navigator.language ?? ''
    return language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}
